#!/usr/bin/env python3
"""Regenerate CatalogData.lua and docs/icon-manifest.json from Blizzard UI source.

The input is Blizzard_ChatFrameBase/Mainline/ChatEmoteConstants.lua from the
UI source of the target client (for example a checkout of the Forever branch of
a wow-ui-source mirror, or files exported with the in-game
`exportInterfaceFiles code` console command).

Only facts are extracted: emote token identifiers, their EMOTE<n> index, and
membership in Blizzard's Emote / Voice Emote menu lists. No Blizzard code or
art is copied into the addon.

Usage:
  python scripts/extract_catalog.py <ChatEmoteConstants.lua> <client-version>
  e.g. python scripts/extract_catalog.py .../ChatEmoteConstants.lua 1.60.1.70862
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse(src: str):
    def list_block(name):
        m = re.search(name + r"\s*=\s*\{(.*?)\};", src, re.S)
        if not m:
            raise SystemExit(f"could not find {name}")
        return re.findall(r'"([A-Z0-9_]+)"', m.group(1))

    emote_menu = list_block("EmoteList")
    voice_menu = list_block("TextEmoteSpeechList")
    # Faction voice emotes are appended at runtime by Blizzard per faction.
    for tok in ("FORTHEALLIANCE", "FORTHEHORDE"):
        if re.search(r'TextEmoteSpeechList\[#TextEmoteSpeechList \+ 1\] = "' + tok + '"', src):
            voice_menu.append(tok)
    tokens = [(int(i), t) for i, t in re.findall(r'EMOTE(\d+)_TOKEN\s*=\s*"([A-Z0-9_]+)"', src)]
    max_index = int(re.search(r"MAXEMOTEINDEX\s*=\s*(\d+)", src).group(1))
    return tokens, emote_menu, voice_menu, max_index


def write_lua(tokens, emote_menu, voice_menu, max_index, version):
    lines = [
        "-- GENERATED by scripts/extract_catalog.py. Do not edit by hand.",
        f"-- Source: Blizzard_ChatFrameBase/Mainline/ChatEmoteConstants.lua, client {version}.",
        "-- Facts only (token identifiers, indices, menu membership). Used as a fallback",
        "-- when the client's own EMOTE<n>_TOKEN globals cannot be read at runtime.",
        "local _, ns = ...",
        "",
        "ns.CatalogData = {",
        f'\tclientVersion = "{version}",',
        f"\tmaxIndex = {max_index},",
        "\ttokens = {",
    ]
    for i, t in tokens:
        lines.append(f'\t\t{{ {i}, "{t}" }},')
    lines.append("\t},")
    lines.append("\temoteMenu = { " + ", ".join(f'"{t}"' for t in emote_menu) + " },")
    lines.append("\tvoiceMenu = { " + ", ".join(f'"{t}"' for t in voice_menu) + " },")
    lines.append("}")
    (ROOT / "CatalogData.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_manifest(tokens, emote_menu, voice_menu, version):
    seen = []
    for _, t in tokens:
        if t != "UNUSED" and t not in seen:
            seen.append(t)
    # Tokens whose art may be shared because they are the same gesture.
    shared = {
        "FORTHEHORDE": "for_the_faction",
        "FORTHEALLIANCE": "for_the_faction",
        "TALKEX": "talk",
        "TALKQ": "talk",
        "YW": "welcome",
    }
    priority = ["HELLO", "THANK", "WAVE", "POINT", "LAUGH", "CHEER"]
    entries = []
    for t in seen:
        cats = []
        if t in emote_menu:
            cats.append("emotes")
        if t in voice_menu:
            cats.append("voice")
        if not cats:
            cats.append("text")
        art = shared.get(t, t.lower())
        entries.append({
            "token": t,
            "categories": cats,
            "art_key": art,
            "source_png": f"art/source/{art}.png",
            "runtime_file": f"Media/Icons/{art}.tga",
            "batch": 1 if t in priority else 3,
            "status": "pending",
        })
    manifest = {
        "schema": 1,
        "catalog_source": f"Blizzard_ChatFrameBase/Mainline/ChatEmoteConstants.lua (client {version})",
        "source_format": "PNG, 256x256, RGBA, transparent background",
        "runtime_format": "TGA, 32-bit RGBA, uncompressed or RLE, power-of-two (64x64 or 128x128)",
        "fallbacks": [
            {"key": "generic", "source_png": "art/source/_generic.png", "runtime_file": "Media/Icons/_generic.tga", "batch": 1, "status": "pending"},
            {"key": "category_emotes", "source_png": "art/source/_category_emotes.png", "runtime_file": "Media/Icons/_category_emotes.tga", "batch": 1, "status": "pending"},
            {"key": "category_voice", "source_png": "art/source/_category_voice.png", "runtime_file": "Media/Icons/_category_voice.tga", "batch": 1, "status": "pending"},
        ],
        "entries": entries,
    }
    (ROOT / "docs" / "icon-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    return len(entries)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    tokens, emote_menu, voice_menu, max_index = parse(src)
    write_lua(tokens, emote_menu, voice_menu, max_index, sys.argv[2])
    n = write_manifest(tokens, emote_menu, voice_menu, sys.argv[2])
    print(f"{len(tokens)} token indices, {n} unique emotes, {len(emote_menu)} emote-menu, {len(voice_menu)} voice-menu")


if __name__ == "__main__":
    main()
